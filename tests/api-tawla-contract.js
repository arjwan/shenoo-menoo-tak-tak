const tawla = require('../server/src/games/tawla-engine.js');
function assert(cond, msg) { if (!cond) throw new Error('FAIL: ' + msg); }
console.log('1) create');
const s = tawla.createGame({ playerIds: ['pA', 'pB'] });
assert(s.engine === 'tawla' || s.engine === undefined, 'tawla engine');
assert(s.status === 'waiting', 'waiting');
assert(Array.isArray(s.board) && s.board.length === 24, '24 points');
console.log('2) board counts sum to 15 per side (start)');
const whiteStart = s.board.reduce((sum, p) => sum + (p.white || 0), 0);
const blackStart = s.board.reduce((sum, p) => sum + (p.black || 0), 0);
assert(whiteStart === 15, 'white 15 at start');
assert(blackStart === 15, 'black 15 at start');
console.log('3) bar/home zero');
assert(s.bar && s.bar.white === 0 && s.bar.black === 0, 'bar zero');
console.log('4) dice [0,0] initially');
assert(Array.isArray(s.dice) && s.dice.length === 2, 'dice array');
console.log('5) public state');
const pub = tawla.getPublicState(s);
assert(pub.status === 'waiting', 'public status');
assert(pub.turn === null, 'opening roll decides first turn');
assert(Array.isArray(pub.board) && pub.board.length === 24, 'public board 24');
assert(typeof pub.dice !== 'undefined', 'dice in public');
console.log('6) private state');
const privA = tawla.getPrivateState(s, 'pA');
assert(privA.myColor === 'white', 'myColor white');
const privB = tawla.getPrivateState(s, 'pB');
assert(privB.myColor === 'black', 'myColor black');
console.log('7) no leak: public has no myColor');
assert(!pub.myColor, 'public no myColor');
console.log('8) opening action belongs to first player');
s.status = 'active';
const openingActions = tawla.getLegalActions(s, 'pA');
assert(openingActions.some(action => action.type === 'opening-roll'), 'pA opening roll');
assert(!tawla.getLegalActions(s, 'pB').some(action => action.type === 'opening-roll'), 'pB waits');
console.log('9) deterministic roll action');
const active = tawla.createGame({ playerIds: ['pA', 'pB'], preferredStarter: 'pA' });
active.status = 'active';
const originalRandom = Math.random;
Math.random = () => 0;
const rollRes = tawla.applyAction(active, 'pA', { type: 'roll' });
Math.random = originalRandom;
assert(rollRes && !rollRes.error, 'roll ok');
assert(active.dice[0] === 1 && active.dice[1] === 1, 'dice rolled');
console.log('10) legal move accepted by authoritative engine');
const legals = tawla.getLegalActions(active, 'pA');
assert(legals.length > 0, 'legal moves available');
const moveRes = tawla.applyAction(active, 'pA', legals[0]);
assert(moveRes && !moveRes.error, 'move ok');
console.log('ALL TAWLA CONTRACT TESTS PASS');
