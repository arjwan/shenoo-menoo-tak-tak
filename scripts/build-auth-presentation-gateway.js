'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const assets = {};
for (const name of ['signin.html', 'signup.html', 'auth-ui.css', 'auth-preview.html', 'taktak.html', 'taktak-colors.css', 'site-ui.css']) {
  assets['/' + name] = fs.readFileSync(path.join(root, name), 'utf8');
}
const helper = fs.readFileSync(path.join(root, 'cloudflare/auth-presentation.js'), 'utf8');
let proxy = fs.readFileSync(path.join(root, 'cloudflare/oracle-domain-proxy.mjs'), 'utf8');
if (!proxy.includes('  const incoming=new URL(request.url);')) {
  throw new Error('Gateway source changed; review presentation insertion points.');
}
proxy = proxy.replace('  const incoming=new URL(request.url);', '  const incoming=new URL(request.url);\n  const presentation=authPresentationResponse(incoming.pathname,request);\n  if(presentation) return presentation;');
const siteHelper = fs.readFileSync(path.join(root, 'cloudflare/site-presentation.js'), 'utf8');
proxy = proxy.replace('if(presentation) return presentation;', 'if(presentation) return sitePresentationResponse(presentation, incoming.pathname);');
proxy = proxy.replace('  return response;\n }\n};', '  return sitePresentationResponse(response, incoming.pathname);\n }\n};');
const result = '// Generated by scripts/build-auth-presentation-gateway.js.\nconst UI_ASSETS=' + JSON.stringify(assets) + ';\n' + helper + '\n' + siteHelper + '\n' + proxy;
fs.writeFileSync(path.join(root, 'cloudflare/oracle-domain-gateway.mjs'), result);
console.log('Built authentication presentation gateway. Auth API requests still use the existing Oracle backend.');
